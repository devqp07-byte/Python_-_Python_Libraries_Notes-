"""
===========================
PYTHON VARIABLE – NOTES
===========================

Definition:
A variable is a name used to store data
in a program. The value of a variable
can be changed during execution.
"""

# ------------------------
# Creating Variables
# ------------------------
x = 10
name = "Python"
price = 99.5

# ------------------------
# Rules for Naming Variablrr?es
# ------------------------
"""
1. Variable name must start with a letter or underscore (_)
2. Variable name cannot start with a number
3. Only letters, numbers, and underscore allowed
4. No spaces allowed
5. Variable names are case-sensitive
"""

# ------------------------
# Valid Variable Names
# ------------------------
a = 10
_name = "Dev"
total_marks = 500

# ------------------------
# Invalid Variable Names
# ------------------------
"""
2name     ❌
total marks ❌
@price    ❌
"""

# ------------------------
# Multiple Assignment
# ------------------------
a, b, c = 1, 2, 3

# ------------------------
# Same Value to Multiple Variables
# ------------------------
x = y = z = 100

# ------------------------
# Variable Type Changes
# ------------------------
x = 10
x = "Python"   # Type can change

