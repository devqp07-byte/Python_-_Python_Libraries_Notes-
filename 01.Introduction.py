## Definition:
# Python is a high-level, interpreted, general-purpose programming language.
# It is designed to be simple, readable, and easy to learn.

# History:
# - Created by: Guido van Rossum
# - Year: 1991
# - Developed in: Netherlands
# - Python was developed at CWI (Centrum Wiskunde & Informatica)

# Name Origin:
# - The name "Python" is not taken from the snake
# - It is based on the TV show "Monty Python’s Flying Circus"
# - That is why Python documentation uses humor

# --------------------------------
# Important Terms Explained
# --------------------------------

# High-Level Language:
# A high-level language is a programming language
# that is easy for humans to read and write.
# It hides hardware details from the user.

# Interpreted Language:
# An interpreted language executes code
# line by line without compiling the whole program first.
# Errors are shown immediately.

# General-Purpose Language:
# A general-purpose language can be used
# to build different types of applications
# like websites, software, automation, and AI.

# --------------------------------
# Features of Python
# --------------------------------
# 1. Simple and easy syntax
# 2. Interpreted language
# 3. Open-source and free
# 4. High-level language
# 5. Portable (runs on many platforms)
# 6. Object-Oriented Programming supported
# 7. Large standard library

# --------------------------------
# Applications of Python
# --------------------------------
# - Web development
# - Data science and machine learning
# - Automation and scripting
# - Software development
# - Game development

# --------------------------------
# Why Python is Popular
# --------------------------------
# - Easy to understand
# - Less code required
# - Large community support
# - Used in real-world applications

# --------------------------------
# Compiler vs Interpreter
# --------------------------------

# Compiler:
# A compiler translates the entire program
# into machine code at once before execution.
# Errors are shown after compilation is complete.

# Examples:
# - C
# - C++

# Interpreter:
# An interpreter translates and executes
# the program line by line.
# Errors are shown immediately at the line
# where the mistake occurs.

# Examples:
# - Python
# - JavaScript

# What Python Uses:
# Python uses an INTERPRETER, not a compiler.
# That is why Python code runs line by line
# and is easy to debug.

# IMPORTANT:
# Python code is first converted into bytecode,
# then executed by the Python Interpreter.

