"""
===========================
PYTHON DATA TYPES – NOTES
===========================

Definition:
Data types define the type of data
that a variable can store in Python.
"""

# ------------------------
# Numeric Data Types
# ------------------------
"""
1. int      -> Integer numbers (10, -5)
2. float    -> Decimal numbers (3.5, 10.0)
3. complex  -> Complex numbers (2+3j)
"""

# ------------------------
# Text Data Type
# ------------------------
"""
4. str -> Used to store text or characters
"""

# ------------------------
# Sequence Data Types
# ------------------------
"""
5. list  -> Ordered and mutable collection
6. tuple -> Ordered and immutable collection
"""

# ------------------------
# Set Data Type
# ------------------------
"""
7. set -> Unordered collection of unique values
"""

# ------------------------
# Mapping Data Type
# ------------------------
"""
8. dict -> Stores data in key-value pairs
"""

# ------------------------
# Boolean Data Type
# ------------------------
"""
9. bool -> Represents True or False
"""

# ------------------------
# Special Data Type
# ------------------------
"""
10. NoneType -> Represents no value (None)
"""

# ------------------------
# Mutable and Immutable
# ------------------------
"""
Mutable:
Data types whose values can be changed
after creation are called mutable.

Examples:
- list
- set
- dict

Immutable:
Data types whose values cannot be changed
after creation are called immutable.

Examples:
- int
- float
- str
- tuple
"""

# ------------------------
# Index Numbering
# ------------------------
"""
Index:
Index is the position number of an element.

- Index starts from 0
- Used in ordered data types

Examples:
- list
- tuple
- string

Note:
Set and Dictionary do NOT support indexing
because they are unordered.
"""

# ------------------------
# Important Points
# ------------------------
"""
1. Python is dynamically typed
2. Data type is decided at runtime
3. One variable can store different data types
4. Use type() to check data type
"""

"""
SUMMARY:
- Data types define the kind of value stored
- Some data types are mutable, some immutable
- Indexing starts from 0
- Python automatically assigns data types
"""
